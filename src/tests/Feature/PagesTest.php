<?php

it('открывает информационную страницу', function (string $slug, string $heading) {
    $this->get('/pages/'.$slug)
        ->assertOk()
        ->assertSee($heading, false);
})->with([
    'о компании' => ['about', 'О компании'],
    'контакты' => ['contacts', 'Контакты'],
    'доставка' => ['delivery', 'Доставка и оплата'],
    'конфиденциальность' => ['privacy', 'Политика конфиденциальности'],
    'возврат' => ['returns', 'Возврат и обмен'],
    'соглашение' => ['terms', 'Пользовательское соглашение'],
]);
